#!/usr/bin/env bash
# Labels from adapters/claude-code/list_recent_sessions.sh (atrium-issues #152):
# the session's own title wins (latest custom-title, else ai-title, else
# summary), else the first real prompt — never the compaction preamble or a
# harness turn. Labels are cut by character, JSON escapes are undone exactly
# once, and the reply is strict UTF-8 JSON.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FIXTURE_HOME="$(mktemp -d /tmp/atrium-claude-labels.XXXXXX)"
trap 'rm -rf "$FIXTURE_HOME"' EXIT

for dependency in perl python3; do
  if ! command -v "$dependency" >/dev/null 2>&1; then
    printf '[FAIL] missing test dependency: %s\n' "$dependency"
    exit 1
  fi
done

CWD="/Users/fixture/dev/labels"
PROJECT="${FIXTURE_HOME}/.claude/projects/-Users-fixture-dev-labels"
mkdir -p "$PROJECT"

# Fixtures are written the way Claude Code writes them: compact JSON, raw
# UTF-8 (no \u escapes for non-ASCII), one record per line.
python3 - "$PROJECT" "$CWD" <<'PY'
import json, os, sys

project, cwd = sys.argv[1], sys.argv[2]
PREAMBLE = ("This session is being continued from a previous conversation that ran "
            "out of context. The summary below covers the earlier portion of the conversation.")

def user(sid, content, **extra):
    return {"parentUuid": None, "isSidechain": False, "type": "user",
            "message": {"role": "user", "content": content},
            "uuid": f"{sid}-u", "cwd": cwd, "sessionId": sid, **extra}

def meta(kind, sid, **fields):
    return {"type": kind, **fields, "sessionId": sid}

def assistant(sid, text):
    return {"type": "assistant", "message": {"role": "assistant",
            "content": [{"type": "text", "text": text}]}, "sessionId": sid}

def write(sid, records):
    with open(os.path.join(project, f"{sid}.jsonl"), "w", encoding="utf-8") as f:
        for record in records:
            f.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n")

write("cjk-path", [user("cjk-path",
    "我现在面临一些困难，我刚搞完中期答辩ppt\\midterm\\组会记录，想请你帮我整理一下这些材料，然后把重点内容总结成一份报告，再给导师发过去。最后请检查一下格式是否正确。")])

# Pure CJK: three bytes a character, so any byte-wise cut lands mid-character.
write("cjk-plain", [user("cjk-plain", "我现在有一个问题，我前段时间就开始想写论文，啥时候能写完呢？" * 3)])

write("titled", [
    user("titled", "first prompt text"),
    meta("custom-title", "titled", customTitle="Old title"),
    meta("ai-title", "titled", aiTitle="AI title"),
    meta("custom-title", "titled", customTitle="Middle title"),
    meta("custom-title", "titled", customTitle="最终标题"),
])

write("cleared-title", [
    user("cleared-title", "a prompt"),
    meta("custom-title", "cleared-title", customTitle="Renamed"),
    meta("ai-title", "cleared-title", aiTitle="AI chosen title"),
    meta("custom-title", "cleared-title", customTitle=""),
])

write("compacted", [
    {"type": "system", "subtype": "compact_boundary", "parentUuid": None,
     "cwd": cwd, "sessionId": "compacted"},
    user("compacted", PREAMBLE + "\n\nSummary:\n1. Primary Request", isCompactSummary=True,
         isVisibleInTranscriptOnly=True),
    user("compacted", "<local-command-caveat>Caveat: generated by local commands</local-command-caveat>"),
    user("compacted", [{"type": "tool_result", "tool_use_id": "t1", "content": "ok"}]),
    user("compacted", "[Request interrupted by user]"),
    user("compacted", [{"type": "text", "text": "<system-reminder>ignore</system-reminder>"},
                       {"type": "text", "text": "Real prompt after compaction"}]),
])

write("preamble-no-flag", [
    user("preamble-no-flag", PREAMBLE),
    user("preamble-no-flag", "Second real prompt"),
])

write("summary-only", [
    {"type": "summary", "summary": "Legacy summary title", "leafUuid": "x"},
    user("summary-only", "the prompt"),
])

write("dictated", [user("dictated", "<dictated>Fix the login page</dictated> please")])

write("quotes-emoji", [user("quotes-emoji", 'Fix the "quoted" thing \U0001F680 now')])

write("command-args", [user("command-args",
    "<command-message>foo</command-message>\n<command-name>/foo</command-name>\n"
    "<command-args>do the thing</command-args>")])

write("bare-command", [user("bare-command",
    "<command-name>/clear</command-name>\n<command-message>clear</command-message>\n"
    "<command-args></command-args>")])

# Over the 64 KB tail window: a title re-appended at the end is read from the
# tail, a title written only near the start is read from the head.
filler = [assistant(sid, "x" * 2000) for sid in ["pad"] * 60]
write("tail-title", [user("tail-title", "tail prompt")] + filler
      + [meta("custom-title", "tail-title", customTitle="Title from the tail")])
write("head-title", [user("head-title", "head prompt"),
                     meta("custom-title", "head-title", customTitle="Title from the head")] + filler)
PY

OUTPUT_FILE="${FIXTURE_HOME}/output.json"
env HOME="$FIXTURE_HOME" bash "$ROOT/adapters/claude-code/list_recent_sessions.sh" "$CWD" >"$OUTPUT_FILE"

python3 - "$OUTPUT_FILE" <<'PY'
import json, sys

raw = open(sys.argv[1], "rb").read()
try:
    names = {s["id"]: s["name"] for s in json.loads(raw.decode("utf-8"))["sessions"]}
except (UnicodeDecodeError, ValueError) as error:
    print(f"[FAIL] reply is not strict UTF-8 JSON: {error}")
    sys.exit(1)
print("[PASS] reply is strict UTF-8 JSON")

expected = {
    "titled": "最终标题",
    "cleared-title": "AI chosen title",
    "compacted": "Real prompt after compaction",
    "preamble-no-flag": "Second real prompt",
    "summary-only": "Legacy summary title",
    "quotes-emoji": 'Fix the "quoted" thing \U0001F680 now',
    "command-args": "do the thing",
    "dictated": "Fix the login page please",
    "bare-command": "/clear",
    "tail-title": "Title from the tail",
    "head-title": "Title from the head",
}
failures = 0
for sid, want in expected.items():
    got = names.get(sid)
    if got == want:
        print(f"[PASS] {sid}: {got!r}")
    else:
        print(f"[FAIL] {sid}: expected {want!r}, got {got!r}")
        failures += 1

plain = names.get("cjk-plain") or ""
if plain.startswith("我现在有一个问题") and plain.endswith("\u2026") and len(plain) == 80:
    print(f"[PASS] cjk-plain cut at 80 characters: {plain!r}")
else:
    print(f"[FAIL] cjk-plain should be cut at 80 characters: {plain!r}")
    failures += 1

cjk = names.get("cjk-path") or ""
checks = [
    ("starts with the prompt", cjk.startswith("我现在面临一些困难，我刚搞完中期答辩ppt\\midterm\\组会记录")),
    ("cut by character with an ellipsis", cjk.endswith("…") and len(cjk) <= 80),
    ("no replacement characters", "�" not in cjk),
]
for label, ok in checks:
    print(f"[{'PASS' if ok else 'FAIL'}] cjk-path {label}: {cjk!r}")
    failures += 0 if ok else 1
sys.exit(1 if failures else 0)
PY
